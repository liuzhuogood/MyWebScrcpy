package mdscript

import (
	"fmt"
	"strconv"
	"strings"
	"time"
)

// Compiler 负责将 Markdown 流程转译为稳态 Python 脚本
type Compiler struct{}

func NewCompiler() *Compiler {
	return &Compiler{}
}

// ShouldRecompile 检查是否需要重新生成 Python 脚本 (版本一致则复用)
func (c *Compiler) ShouldRecompile(extractedVer, compiledVer, compiledPython string) bool {
	if strings.TrimSpace(compiledPython) == "" {
		return true
	}
	if strings.TrimSpace(compiledVer) == "" {
		return true
	}
	return extractedVer != compiledVer
}

// Compile 生成符合标准的稳态 Python 脚本
func (c *Compiler) Compile(scriptName string, meta ParsedMeta, content string) (string, error) {
	lines := strings.Split(content, "\n")
	var pySteps []string

	stepIdx := 1
	for i := 0; i < len(lines); i++ {
		trimmed := strings.TrimSpace(lines[i])
		if !strings.HasPrefix(trimmed, "- ") {
			continue
		}
		rawStep := strings.TrimPrefix(trimmed, "- ")

		// 如果下一行包含模板标记，合并判定
		checkText := rawStep
		if i+1 < len(lines) && strings.Contains(lines[i+1], "template://") {
			checkText += " " + strings.TrimSpace(lines[i+1])
		}

		// 判断是否包含模板匹配图片
		tmplMatches := reTemplate.FindStringSubmatch(checkText)
		if len(tmplMatches) > 3 {
			tmplID := tmplMatches[3]
			th := 0.85
			if len(tmplMatches) > 4 && tmplMatches[4] != "" {
				fmt.Sscanf(tmplMatches[4], "%f", &th)
			}
			stepCode := fmt.Sprintf(`    # Step %d: 视觉模板匹配
    print(%s)
    target = matcher.wait_and_click(%s, threshold=%.2f, timeout=10.0)
    if not target:
        raise RuntimeError(%s)
    time.sleep(1.0)`, stepIdx, strconv.Quote(fmt.Sprintf("[Step %d] 寻找并点击模板: %s (阈值: %.2f)", stepIdx, tmplID, th)), strconv.Quote(tmplID), th, strconv.Quote("未匹配到指定模板画面: "+tmplID))
			pySteps = append(pySteps, stepCode)
		} else {
			// 普通文字控制流
			stepCode := fmt.Sprintf(`    # Step %d
    print(%s)
    dev.log(%s)
    time.sleep(1.0)`, stepIdx, strconv.Quote(fmt.Sprintf("[Step %d] 执行操作: %s", stepIdx, rawStep)), strconv.Quote(rawStep))
			pySteps = append(pySteps, stepCode)
		}
		stepIdx++
	}

	stepsJoined := strings.Join(pySteps, "\n\n")
	if stepsJoined == "" {
		stepsJoined = "    print(\"[Notice] 未解析到具体执行步骤\")"
	}

	nowStr := time.Now().Format("2006-01-02 15:04:05")
	pythonTemplate := fmt.Sprintf(`# -*- coding: utf-8 -*-
"""
Generated by MyWebScrcpy Markdown Compiler (Pi Engine)
Target Device: runtime argument
"""
SCRIPT_NAME = %s
VERSION = %s
GENERATED_AT = %s
SCHEDULE = %s
TIMEOUT_SEC = %d
import sys
import time
import subprocess

class Device:
    def __init__(self, serial: str):
        self.serial = serial

    @classmethod
    def connect(cls, serial: str):
        return cls(serial)

    def is_screen_on(self) -> bool:
        return True

    def wake_up(self):
        print(f"[Device] 唤醒设备: {self.serial}")

    def log(self, msg: str):
        print(f"[Device {self.serial}] {msg}")

class Matcher:
    def __init__(self, dev: Device):
        self.dev = dev

    def wait_and_click(self, template_id: str, threshold: float = 0.85, timeout: float = 10.0) -> bool:
        print(f"[Matcher] 正在识别模板 {template_id}，阈值: {threshold}")
        return True

def run(serial: str) -> bool:
    print(f"[Starting] 正在启动脚本: {SCRIPT_NAME} (版本: {VERSION})...")
    dev = Device.connect(serial)
    matcher = Matcher(dev)

    # 前置状态检查与保活
    if not dev.is_screen_on():
        print("[Setup] 唤醒屏幕...")
        dev.wake_up()
        time.sleep(1.0)

%s

    print("[Success] 脚本执行完毕")
    return True

if __name__ == "__main__":
    # 独立运行生成脚本时也统一日志编码。
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    if len(sys.argv) != 2:
        raise SystemExit("Usage: script.py <device_serial>")
    run(sys.argv[1])
`, strconv.Quote(scriptName), strconv.Quote(meta.ExtractedVersion), strconv.Quote(nowStr), strconv.Quote(meta.ScheduleCron), meta.TimeoutSec, stepsJoined)

	return pythonTemplate, nil
}
